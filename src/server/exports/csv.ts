/**
 * CSV serializer (pure): UTF-8 with BOM (so Excel detects the encoding), CRLF line endings,
 * RFC 4180 quoting, one header row. Every text cell is sanitised against formula injection.
 */
import { cellDisplayText, type ExportCellValue } from "./columns";
import { sanitizeCellText } from "./sanitize";

export const CSV_BOM = "﻿";
const NEEDS_QUOTES = /[",\r\n]/;

/** One CSV field: sanitised text, quoted (with doubled quotes) when it contains a separator, quote or newline. */
export function csvField(value: ExportCellValue): string {
  if (value == null) return "";
  // Numbers and dates are generated by us, never user text; strings are untrusted.
  const raw = typeof value === "string" ? sanitizeCellText(value) : cellDisplayText(value);
  return NEEDS_QUOTES.test(raw) || raw !== raw.trim() ? `"${raw.replace(/"/g, '""')}"` : raw;
}

export function buildCsv(headers: readonly string[], rows: readonly (readonly ExportCellValue[])[]): Buffer {
  const lines: string[] = [headers.map((h) => csvField(h)).join(",")];
  for (const row of rows) lines.push(row.map(csvField).join(","));
  return Buffer.from(CSV_BOM + lines.join("\r\n") + "\r\n", "utf8");
}
